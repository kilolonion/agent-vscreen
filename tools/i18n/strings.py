#!/usr/bin/env python3
"""
The app's text table: app/src/main/resources/i18n/strings.tsv, one row per text.

    key <TAB> scope <TAB> zh <TAB> en <TAB> ja [<TAB> more languages…]

- key: the name code uses, as S.<key> (S.kt is generated from this file: run this script after editing it).
- scope: `ui` (people read it: every language column must be filled) or `agent` (only agents read it; agent
  replies are Chinese or English, so later columns may stay empty and fall back to English).
- texts: `{0}`, `{1}` are the values the call passes, in the order of tr(S.key, a, b); a language may reorder or
  repeat them. A newline is written as ⏎. No tabs.

Adding a language: add a column to the header (its code, e.g. `ko`), fill it for every `ui` row, add the code to
I18n.Lang. Nothing else changes.

    python3 tools/i18n/strings.py          # sort the table, regenerate S.kt
    python3 tools/i18n/strings.py --check  # CI: S.kt current, columns filled, holes valid, every key used, no inline pairs in ui/ host/
"""
import os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
TSV = os.path.join(ROOT, 'app', 'src', 'main', 'resources', 'i18n', 'strings.tsv')
JAVA = os.path.join(ROOT, 'app', 'src', 'main', 'java', 'com', 'kilon', 'agentvscreen')
SKT = os.path.join(JAVA, 'S.kt')
HOLE = re.compile(r'\{(\d+)\}')
KEY = re.compile(r'^[a-z][a-z0-9_]*$')


def load():
    with open(TSV, encoding='utf-8') as f:
        lines = f.read().split('\n')
    head = lines[0].split('\t')
    if head[:4] != ['key', 'scope', 'zh', 'en']:
        sys.exit('strings.tsv: the header must start with key, scope, zh, en')
    rows = []
    for n, line in enumerate(lines[1:], 2):
        if not line:
            continue
        cells = line.split('\t')
        if len(cells) > len(head):
            sys.exit(f'strings.tsv:{n}: more cells than header columns (a tab inside a text?)')
        cells += [''] * (len(head) - len(cells))
        rows.append((n, cells))
    return head, rows


def save(head, rows):
    rows = sorted(rows, key=lambda r: r[1][0])
    with open(TSV, 'w', encoding='utf-8') as f:
        f.write('\t'.join(head) + '\n')
        for _, cells in rows:
            while len(cells) > 4 and cells[-1] == '':
                cells = cells[:-1]
            f.write('\t'.join(cells) + '\n')
    return rows


def kotlin(head, rows):
    out = ['// Generated by tools/i18n/strings.py from app/src/main/resources/i18n/strings.tsv. Do not edit.',
           'package com.kilon.agentvscreen', '',
           '/** Text ids for [tr]: row numbers of the text table (languages: ' + ', '.join(head[2:]) + '). */',
           '@Suppress("unused")', 'object S {']
    for i, (_, cells) in enumerate(rows):
        out.append(f'    const val {cells[0]} = {i}')
    out += ['}', '']
    return '\n'.join(out)


def code_texts():
    for dp, _, fs in os.walk(JAVA):
        for f in fs:
            if f.endswith('.kt') and f != 'S.kt':
                p = os.path.join(dp, f)
                yield os.path.relpath(p, JAVA), open(p, encoding='utf-8').read()


def check(head, rows):
    errs = []
    seen = set()
    for n, c in rows:
        key, scope = c[0], c[1]
        if not KEY.match(key): errs.append(f'{n}: bad key {key!r}')
        if key in seen: errs.append(f'{n}: duplicate key {key}')
        seen.add(key)
        if scope not in ('ui', 'agent'): errs.append(f'{n}: scope must be ui or agent')
        if c[3] == '' and c[2] != '': errs.append(f'{n} {key}: English is empty')
        holes = set(HOLE.findall(c[2])) | set(HOLE.findall(c[3]))
        for lang, text in zip(head[2:], c[2:]):
            if scope == 'ui' and text == '' and (c[2] or c[3]):
                errs.append(f'{n} {key}: no {lang}')
            extra = set(HOLE.findall(text)) - holes
            if extra: errs.append(f'{n} {key}: {lang} uses {{{",".join(sorted(extra))}}} that zh/en do not pass')
    want = kotlin(head, sorted(rows, key=lambda r: r[1][0]))
    if [r[1][0] for r in rows] != sorted(r[1][0] for r in rows):
        errs.append('strings.tsv is not sorted by key: run python3 tools/i18n/strings.py')
    if not os.path.exists(SKT) or open(SKT, encoding='utf-8').read() != want:
        errs.append('S.kt is not generated from strings.tsv: run python3 tools/i18n/strings.py')
    used = set()
    inline = []
    for rel, s in code_texts():
        used |= set(re.findall(r'\bS\.([a-z][a-z0-9_]*)', s))
        if rel.startswith(('ui/', 'host/')):
            for m in re.finditer(r'(?<![A-Za-z0-9_.])tr\(\s*"', s):
                inline.append(f'{rel}:{s.count(chr(10), 0, m.start()) + 1}')
    for k in sorted(seen - used): errs.append(f'unused key {k}')
    for k in sorted(used - seen): errs.append(f'S.{k} is used but not in strings.tsv')
    for w in inline: errs.append(f'{w}: inline tr("中", "En") in ui/ or host/: put the text in strings.tsv and call tr(S.key)')
    for e in errs: print(e)
    if errs:
        sys.exit(f'{len(errs)} problem(s) in the text table')
    ui = sum(1 for _, c in rows if c[1] == 'ui')
    print(f'OK: {len(rows)} texts ({ui} for people, all in {", ".join(head[2:])}; {len(rows) - ui} agent-only)')


def main():
    head, rows = load()
    if '--check' in sys.argv:
        check(head, rows); return
    rows = save(head, rows)
    with open(SKT, 'w', encoding='utf-8') as f:
        f.write(kotlin(head, rows))
    print(f'{len(rows)} texts -> S.kt')


if __name__ == '__main__':
    main()
